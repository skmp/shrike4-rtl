/* seqx.c -- M3 verification: back-to-back access sequences on two lines that share one operand-cache entry, on the
 * whole chip (rm) in lockstep, with a model-free reference: the manual's semantics of one direct-mapped entry and the two
 * lines' memory (hm 4.3: copy-back allocate on a P1 load / store / PREF miss with the dirty victim written back first;
 * write-through with CCR.WT for P0: a hit updates the line and memory, a miss writes memory only; P2 goes to memory;
 * OCBP writes a dirty line back and invalidates, OCBWB writes back and keeps it clean, OCBI invalidates (a dirty line is
 * lost); a store-queue burst writes memory and leaves the cache alone; TAS.B purges the line (OCBP) and makes a locked
 * read / write of memory: T = (byte == 0), byte |= 0x80).
 * The sequences (seqx_asm.S, generated by gen/gen_seqx.py): every ordered pair of the 12 ops on A then A / B, and random
 * sequences of 2 .. 6 ops; each from one of 5 initial entry states (empty, A clean, A dirty, B clean, B dirty) with fresh
 * memory contents.  Every load's value and both lines' final memory are compared with the reference.
 * CCR = ICE | OCE | CB | WT (P1 copy-back, P0 write-through).  Output: "SEQX MISMATCH seq=<k> ..." (the first 30),
 * "SEQX summary seqs=<n> loads=<n> bad=<n>", "SEQX done". */
#include "m3.h"
#include "seqx_tab.h"

extern void seq_run(void (*fn)(void), uint32_t *regs);
extern void (*const seq_tab[NSEQ])(void);

enum { LD1, ST1, LD0, STW, LD2, ST2, PREF, OCBP, OCBWB, OCBI, SQ, TAS };
static const char *const opname[] = {"LD1", "ST1", "LD0", "STW", "LD2", "ST2", "PREF", "OCBP", "OCBWB", "OCBI", "SQ", "TAS"};
/* A and B: one OC entry that no access of the harness between the set-up and the sequence uses (regs[], seed, the
 * stack): picked at start (pick_entry) */
static uint32_t A_PA, B_PA;
static uint32_t regs[16];
static uint32_t mem[2][8];                       /* the reference: the two lines' memory */
static int tag, dirty;                           /* the entry: -1 empty, 0 A, 1 B */
static uint32_t cd[8];
static uint32_t seed = 0xC0FFEEu;
static int nbad, nload;

static void wb(void) { if (tag >= 0 && dirty) for (int w = 0; w < 8; w++) mem[tag][w] = cd[w]; }
static void alloc(int ln) {
  if (tag == ln) return;
  wb();
  tag = ln; dirty = 0;
  for (int w = 0; w < 8; w++) cd[w] = mem[ln][w];
}
static void bad(int k, const char *what, int i, uint32_t got, uint32_t want) {
  nbad++;
  if (nbad <= 30) {
    const seqd_t *s = &seqd[k];
    printf("SEQX MISMATCH seq=%d init=%d %s op#%d got=%08lx want=%08lx :", k, s->init, what, i, (unsigned long)got,
           (unsigned long)want);
    for (int j = 0; j < s->n; j++) printf(" %s%c+%d", opname[s->op[j]], s->ln[j] ? 'B' : 'A', s->off[j]);
    printf("\n");
  }
}

static void one(int k) {
  const seqd_t sl = seqd[k];                     /* copied first: no table read between the set-up and the sequence */
  const seqd_t *s = &sl;
  const uint32_t pa[2] = {A_PA, B_PA};
  /* fresh memory, the entry empty, then the initial state */
  for (int ln = 0; ln < 2; ln++) {
    ocbp(P1(pa[ln]));
    for (int w = 0; w < 8; w++) {
      uint32_t v = lcg(&seed) ^ ((uint32_t)k << 20);
      if (w == 0 && (lcg(&seed) & 1)) v &= 0xFFFFFF00u;   /* byte 0 zero for half the TAS runs */
      R32(P2(pa[ln]) + 4u * (uint32_t)w) = v; mem[ln][w] = v;
    }
  }
  tag = -1; dirty = 0;
  if (s->init == 1 || s->init == 3) { int ln = s->init == 3; (void)R32(P1(pa[ln]) + 4); alloc(ln); }
  if (s->init == 2 || s->init == 4) {
    int ln = s->init == 4; uint32_t v = lcg(&seed);
    R32(P1(pa[ln]) + 12) = v; alloc(ln); cd[3] = v; dirty = 1;
  }
  regs[1] = lcg(&seed) | 1u; regs[2] = lcg(&seed) | 2u; regs[3] = lcg(&seed) | 4u;
  regs[4] = P1(A_PA); regs[5] = P1(B_PA); regs[6] = P2(A_PA); regs[7] = P2(B_PA);
  regs[8] = P0(A_PA); regs[9] = P0(B_PA); regs[10] = regs[11] = regs[12] = 0xDEADDEADu;
  regs[13] = 0xE0000000u | (A_PA & 0x03FFFFE0u); regs[14] = 0xE0000000u | (B_PA & 0x03FFFFE0u);
  seq_run(seq_tab[k], regs);
  /* the reference */
  uint32_t res[3]; int nr = 0;
  for (int i = 0; i < s->n; i++) {
    int ln = s->ln[i], w = s->off[i] >> 2;
    uint32_t v = regs[s->vr[i]];
    switch (s->op[i]) {
    case LD1: case LD0: alloc(ln); res[nr++] = cd[w]; break;
    case ST1: alloc(ln); cd[w] = v; dirty = 1; break;
    case STW: if (tag == ln) cd[w] = v; mem[ln][w] = v; break;
    case LD2: res[nr++] = mem[ln][w]; break;
    case ST2: mem[ln][w] = v; break;
    case PREF: alloc(ln); break;
    case OCBP: if (tag == ln) { wb(); tag = -1; } break;
    case OCBWB: if (tag == ln) { wb(); dirty = 0; } break;
    case OCBI: if (tag == ln) tag = -1; break;
    case SQ: for (int x = 0; x < 8; x++) mem[ln][x] = v; break;
    case TAS: {
      if (tag == ln) { wb(); tag = -1; }
      uint32_t b = mem[ln][0] & 0xFFu;
      res[nr++] = b == 0;
      mem[ln][0] |= 0x80u;
      break;
    }
    }
  }
  for (int i = 0; i < nr; i++) {
    nload++;
    if (regs[10 + i] != res[i]) bad(k, "load", i, regs[10 + i], res[i]);
  }
  /* the final memory: every line written back */
  for (int ln = 0; ln < 2; ln++) ocbp(P1(pa[ln]));
  wb();
  for (int ln = 0; ln < 2; ln++)
    for (int w = 0; w < 8; w++) {
      uint32_t g = R32(P2(pa[ln]) + 4u * (uint32_t)w);
      if (g != mem[ln][w]) bad(k, ln ? "memB" : "memA", w, g, mem[ln][w]);
    }
}

static int ent(uint32_t a) { return (int)((a >> 5) & 0x1FFu); }
static void pick_entry(void) {
  uint32_t sp;
  __asm__ __volatile__("mov r15,%0" : "=r"(sp));
  static uint8_t used[512];
  for (uint32_t a = (uint32_t)(uintptr_t)regs; a < (uint32_t)(uintptr_t)(regs + 16); a += 4) used[ent(a)] = 1;
  used[ent((uint32_t)(uintptr_t)&seed)] = 1;
  used[ent((uint32_t)(uintptr_t)&tag)] = used[ent((uint32_t)(uintptr_t)&dirty)] = 1;
  for (uint32_t a = (uint32_t)(uintptr_t)mem; a < (uint32_t)(uintptr_t)(mem + 2); a += 4) used[ent(a)] = 1;
  for (uint32_t a = (uint32_t)(uintptr_t)cd; a < (uint32_t)(uintptr_t)(cd + 8); a += 4) used[ent(a)] = 1;
  for (uint32_t a = sp - 1024u; a < sp + 256u; a += 4) used[ent(a)] = 1;
  int e = 64;
  while (used[e]) e++;
  A_PA = TR_PA + 0x60000u + 32u * (uint32_t)e;
  B_PA = A_PA + 0x4000u;
  printf("SEQX entry=%d A=%08lx B=%08lx\n", e, (unsigned long)A_PA, (unsigned long)B_PA);
}

int main(void) {
  printf("SEQX start nseq=%d\n", NSEQ);
  pick_entry();
  ccr_set(CCR_ICE | CCR_OCE | CCR_CB | CCR_WT);
  R32(QACR0) = 0x0C; R32(QACR1) = 0x0C;
  for (int k = 0; k < NSEQ; k++) one(k);
  printf("SEQX summary seqs=%d loads=%d bad=%d\n", NSEQ, nload, nbad);
  printf("SEQX done\n");
  return nbad ? 1 : 0;
}
