#!/usr/bin/env python3
"""gen_irqx.py -- writes $(OUT)/m3/irqx_asm.S (tb/bm/soc-adv/Makefile): irqx.c's code block (M3 verification).

One straight-line routine `_blk` of ~NINS instructions (larger than the 8 KB I-cache, so every pass misses it), a
deterministic random mix over r0-r7 with fixed bases: r8 / r9 = two operand-cache aliases (16 KB apart), r10 = byte /
word traffic, r11 = PREF / OCBWB / OCBP lines, r12 = a store-queue address, r13 = an odd address (a misaligned load: the
handler skips it, g_skip), r14 = the loop's line walk.  Forward branches (BRA / BT / BF with delay slots) break the
stream into redirects; TRAPA #0x20 returns through the handler.  The block is transparent to interrupts: the same
memory image with or without them (irqx.c compares the two)."""
import random, sys
NINS = int(sys.argv[2]) if len(sys.argv) > 2 else 7000
rnd = random.Random(20260925)
out = []
def e(s): out.append('        ' + s)
lab = 0
pending = []            # (label, remaining) forward-branch targets
i = 0
while i < NINS:
    for p in list(pending):
        p[1] -= 1
        if p[1] <= 0:
            out.append(f'{p[0]}:')
            pending.remove(p)
    k = rnd.random()
    ra, rb = rnd.randrange(8), rnd.randrange(8)
    if k < 0.16:
        e(f'mov.l   @({4 * rnd.randrange(16)},r{rnd.choice([8, 9])}),r{ra}')
    elif k < 0.30:
        e(f'mov.l   r{ra},@({4 * rnd.randrange(16)},r{rnd.choice([8, 9])})')
    elif k < 0.36:
        # byte / word traffic through r10 (R0-relative forms need r0: use @(disp,Rn) for W / B with r0 as data)
        if rnd.random() < 0.5:
            e(f'mov.b   r0,@({rnd.randrange(16)},r10)')
        else:
            e(f'mov.w   @({2 * rnd.randrange(16)},r10),r0')
    elif k < 0.50:
        op = rnd.choice(['add', 'xor', 'sub', 'or', 'and', 'addc', 'shll', 'shlr', 'rotl', 'not', 'neg', 'swap.w', 'extu.b', 'mul.l'])
        if op in ('shll', 'shlr', 'rotl'):
            e(f'{op:8s}r{ra}')
        elif op in ('not', 'neg', 'swap.w', 'extu.b'):
            e(f'{op:8s}r{rb},r{ra}')
        elif op == 'mul.l':
            e(f'mul.l   r{rb},r{ra}')
            e(f'sts     macl,r{ra}')
            i += 1
        else:
            e(f'{op:8s}r{rb},r{ra}')
    elif k < 0.55:
        e(f'add     #{rnd.randrange(-128, 128)},r{ra}')
    elif k < 0.58:
        c = rnd.choice(['pref', 'ocbwb', 'ocbp'])
        e(f'{c:8s}@r11')
        e('add     #32,r11')
        i += 1
    elif k < 0.61:
        # a store-queue longword; every 8th a PREF of the queue (the burst)
        e(f'mov.l   r{ra},@({4 * rnd.randrange(8)},r12)')
        if rnd.random() < 0.3:
            e('pref    @r12')
            i += 1
    elif k < 0.615:
        e('trapa   #0x20')
    elif k < 0.62:
        e(f'mov.l   @r13,r{ra}')          # misaligned: the handler skips it
    elif k < 0.66 and not pending:
        lab += 1
        L = f'.Lf{lab}'
        c = rnd.choice(['bra', 'bt', 'bf', 'bt/s', 'bf/s'])
        if c in ('bt', 'bf'):
            e(f'cmp/hi  r{ra},r{rb}')
            e(f'{c:8s}{L}')
            i += 1
        else:
            if c != 'bra':
                e(f'cmp/ge  r{ra},r{rb}')
                i += 1
            e(f'{c:8s}{L}')
            e(f'add     #1,r{rb}')        # the delay slot
            i += 1
        pending.append([L, rnd.randrange(3, 40)])
    elif k < 0.70:
        e(f'mov.l   @r14+,r{ra}')         # the walk (r14 advances 4 per use; irqx.c bounds the passes)
    else:
        e(f'mov     r{rb},r{ra}')
    i += 1
for p in pending:
    out.append(f'{p[0]}:')
hdr = '''/* irqx_asm.S -- GENERATED by tb/bm/soc-adv/m3/gen_irqx.py (M3 verification): irqx.c's code block.
 *   void blk(void)   r8 .. r14 set by the caller (blk_run); r0 .. r7 carry the data */
        .text
        .balign 32
        .global _blk
_blk:
'''
tail = '''        rts
        nop

/* blk_run(regs[8]): r8 .. r14 <- regs[0 .. 6], r0 .. r7 <- seed pattern regs[7] ^ k, blk(), regs[7] <- r0 ^ .. ^ r7
 * (the callee-saved registers are saved and restored) */
        .balign 32
        .global _blk_run
_blk_run:
        mov.l   r8,@-r15
        mov.l   r9,@-r15
        mov.l   r10,@-r15
        mov.l   r11,@-r15
        mov.l   r12,@-r15
        mov.l   r13,@-r15
        mov.l   r14,@-r15
        sts.l   pr,@-r15
        sts.l   macl,@-r15
        mov.l   r4,@-r15
        mov.l   @(0,r4),r8
        mov.l   @(4,r4),r9
        mov.l   @(8,r4),r10
        mov.l   @(12,r4),r11
        mov.l   @(16,r4),r12
        mov.l   @(20,r4),r13
        mov.l   @(24,r4),r14
        mov.l   @(28,r4),r0
        mov     r0,r1
        not     r0,r2
        add     #1,r1
        mov     r1,r3
        shll    r3
        mov     r2,r4
        neg     r4,r4
        mov     r3,r5
        xor     r1,r5
        mov     r5,r6
        rotl    r6
        mov     r6,r7
        add     r2,r7
        mov.l   .Lblk,r0
        jsr     @r0
        nop
        xor     r1,r0
        xor     r2,r0
        xor     r3,r0
        xor     r4,r0
        xor     r5,r0
        xor     r6,r0
        xor     r7,r0
        mov.l   @r15+,r4
        mov.l   r0,@(28,r4)
        mov.l   r14,@(24,r4)
        lds.l   @r15+,macl
        lds.l   @r15+,pr
        mov.l   @r15+,r14
        mov.l   @r15+,r13
        mov.l   @r15+,r12
        mov.l   @r15+,r11
        mov.l   @r15+,r10
        mov.l   @r15+,r9
        rts
        mov.l   @r15+,r8
        .balign 4
.Lblk:  .long   _blk
'''
open(sys.argv[1], 'w').write(hdr + '\n'.join(out) + '\n' + tail)
