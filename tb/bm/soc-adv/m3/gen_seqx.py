#!/usr/bin/env python3
"""gen_seqx.py -- writes $(OUT)/m3/seqx_asm.S and seqx_tab.h (tb/bm/soc-adv/Makefile): seqx.c's back-to-back access sequences
(M3 verification).

Two lines A and B on ONE operand-cache entry (16 KB apart).  Every sequence is 2 .. 6 accesses issued back to back (no
instruction between them but the accesses themselves), so the operand cache's fill queue, WBB, WTB, the store queues and
the BIU's ordering rules see each other's transactions in flight.  Registers in a sequence (seq_run sets them):
  r1 r2 r3   store values          r4 / r5  A / B through P1 (copy-back)    r6 / r7  A / B through P2 (uncached)
  r8 / r9    A / B through P0 (CCR.WT = 1: write-through)                   r10 r11 r12  load results (in order)
  r13 / r14  A / B's store-queue addresses
Ops (seqx.c's reference model applies the manual's semantics to one direct-mapped entry and the two lines' memory):
  LD1 ST1 (P1)  LD0 STW (P0: cached load, write-through store)  LD2 ST2 (P2)  PREF OCBP OCBWB OCBI (P1)
  SQ (8 longword stores into the queue, then PREF)  TAS (TAS.B on the line's byte 0; MOVT into the next result)"""
import random, sys

OPS = ['LD1', 'ST1', 'LD0', 'STW', 'LD2', 'ST2', 'PREF', 'OCBP', 'OCBWB', 'OCBI', 'SQ', 'TAS']
OPN = {n: i for i, n in enumerate(OPS)}
rnd = random.Random(0x5E9)
NRAND = int(sys.argv[3]) if len(sys.argv) > 3 else 1400


def one(op, ln, off, vreg, dreg):
    """asm for one op on line ln (0 A, 1 B); returns (lines, uses a result register)"""
    p1, p2, p0, sq = (4 + ln), (6 + ln), (8 + ln), (13 + ln)
    if op == 'LD1': return [f'mov.l   @({off},r{p1}),r{dreg}'], True
    if op == 'LD0': return [f'mov.l   @({off},r{p0}),r{dreg}'], True
    if op == 'LD2': return [f'mov.l   @({off},r{p2}),r{dreg}'], True
    if op == 'ST1': return [f'mov.l   r{vreg},@({off},r{p1})'], False
    if op == 'STW': return [f'mov.l   r{vreg},@({off},r{p0})'], False
    if op == 'ST2': return [f'mov.l   r{vreg},@({off},r{p2})'], False
    if op == 'PREF': return [f'pref    @r{p1}'], False
    if op == 'OCBP': return [f'ocbp    @r{p1}'], False
    if op == 'OCBWB': return [f'ocbwb   @r{p1}'], False
    if op == 'OCBI': return [f'ocbi    @r{p1}'], False
    if op == 'SQ':
        return [f'mov.l   r{vreg},@({4 * w},r{sq})' for w in range(8)] + [f'pref    @r{sq}'], False
    if op == 'TAS': return [f'tas.b   @r{p1}', f'movt    r{dreg}'], True
    raise ValueError(op)


seqs = []
# every ordered pair of (op, line) with line A first, then random sequences
pairs = [(a, b) for a in OPS for b in OPS]
for a, b in pairs:
    for lb in (0, 1):
        seqs.append([(a, 0), (b, lb)])
for _ in range(NRAND):
    n = rnd.randrange(2, 7)
    seqs.append([(rnd.choice(OPS), rnd.randrange(2)) for _ in range(n)])

asm = ['/* seqx_asm.S -- GENERATED by tb/bm/soc-adv/m3/gen_seqx.py (M3 verification): seqx.c\'s sequences. */',
       '        .text']
tab = ['/* seqx_tab.h -- GENERATED by tb/bm/soc-adv/m3/gen_seqx.py (M3 verification). */',
       f'#define NSEQ {len(seqs)}', '#define MAXOP 6',
       'typedef struct { uint8_t n, init; uint8_t op[MAXOP], ln[MAXOP], off[MAXOP], vr[MAXOP]; } seqd_t;',
       'static const seqd_t seqd[NSEQ] = {']
for k, s in enumerate(seqs):
    asm.append('        .balign 32')
    asm.append(f'_seq_{k}:')
    dreg = 10
    ops, lns, offs, vrs = [], [], [], []
    for (op, ln) in s:
        off = 4 * rnd.randrange(8)
        vr = rnd.randrange(1, 4)
        code, uses = one(op, ln, off, vr, dreg)
        if uses:
            if dreg > 12:            # at most three results: turn later loads into stores of the same line
                op = 'ST1' if op in ('LD1', 'LD0', 'TAS') else 'ST2'
                code, uses = one(op, ln, off, vr, dreg)
            else:
                dreg += 1
        for c in code:
            asm.append('        ' + c)
        ops.append(OPN[op]); lns.append(ln); offs.append(off); vrs.append(vr)
    asm.append('        rts')
    asm.append('        nop')
    init = rnd.randrange(5)          # 0 empty, 1 A clean, 2 A dirty, 3 B clean, 4 B dirty
    pad = lambda v: v + [0] * (6 - len(v))
    tab.append('  {%d, %d, {%s}, {%s}, {%s}, {%s}},' % (len(s), init, ','.join(map(str, pad(ops))),
               ','.join(map(str, pad(lns))), ','.join(map(str, pad(offs))), ','.join(map(str, pad(vrs)))))
tab.append('};')
asm.append('        .balign 4')
asm.append('        .global _seq_tab')
asm.append('_seq_tab:')
for k in range(len(seqs)):
    asm.append(f'        .long   _seq_{k}')
asm.append('''
/* seq_run(fn, regs[16]): r1 .. r14 <- regs[1 .. 14], call fn, regs[10 .. 12] <- r10 .. r12 (r8 .. r14 and PR saved) */
        .balign 32
        .global _seq_run
_seq_run:
        mov.l   r8,@-r15
        mov.l   r9,@-r15
        mov.l   r10,@-r15
        mov.l   r11,@-r15
        mov.l   r12,@-r15
        mov.l   r13,@-r15
        mov.l   r14,@-r15
        sts.l   pr,@-r15
        mov.l   r5,@-r15
        mov     r4,r0
        mov     r5,r4
        mov.l   @(4,r4),r1
        mov.l   @(8,r4),r2
        mov.l   @(12,r4),r3
        mov.l   @(20,r4),r5
        mov.l   @(24,r4),r6
        mov.l   @(28,r4),r7
        mov.l   @(32,r4),r8
        mov.l   @(36,r4),r9
        mov.l   @(40,r4),r10
        mov.l   @(44,r4),r11
        mov.l   @(48,r4),r12
        mov.l   @(52,r4),r13
        mov.l   @(56,r4),r14
        jsr     @r0
        mov.l   @(16,r4),r4
        mov.l   @r15+,r0
        mov.l   r10,@(40,r0)
        mov.l   r11,@(44,r0)
        mov.l   r12,@(48,r0)
        lds.l   @r15+,pr
        mov.l   @r15+,r14
        mov.l   @r15+,r13
        mov.l   @r15+,r12
        mov.l   @r15+,r11
        mov.l   @r15+,r10
        mov.l   @r15+,r9
        rts
        mov.l   @r15+,r8''')
open(sys.argv[1], 'w').write('\n'.join(asm) + '\n')
open(sys.argv[2], 'w').write('\n'.join(tab) + '\n')
print(f'gen_seqx: {len(seqs)} sequences', file=sys.stderr)
