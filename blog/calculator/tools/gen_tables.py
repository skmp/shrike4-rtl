#!/usr/bin/env python3
"""gen_tables.py -- blog/calculator/tables.js from rtl/fpu_vec/fpu_vec_tables.svh, so the calculator's ROMs are the
RTL's ROMs.  Run from anywhere: python3 blog/calculator/tools/gen_tables.py"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
SVH = os.path.join(HERE, "..", "..", "..", "rtl", "fpu_vec", "fpu_vec_tables.svh")
OUT = os.path.join(HERE, "..", "tables.js")
WANT = ["FSCA_A_C0", "FSCA_A_L", "FSCA_A_E", "FSCA_A_Q", "FSCA_B_C0", "FSCA_B_L", "FSCA_B_E", "FSCA_B_Q",
        "FSRRA_C0", "FSRRA_REC1", "FSRRA_E1", "FSRRA_REC2", "FSRRA_REC3"]

def num(tok):
    m = re.fullmatch(r"(\d+)'([hdb])([0-9a-fA-F_]+)", tok.strip())
    base = {"h": 16, "d": 10, "b": 2}[m.group(2)]
    return int(m.group(3).replace("_", ""), base)

src = open(SVH).read()
out = ["// GENERATED by blog/calculator/tools/gen_tables.py from rtl/fpu_vec/fpu_vec_tables.svh -- do not edit.",
       "// FSCA: two 16-word ROMs (word r and word 16-r), fields C0 26b, L 23b, E 2b, Q 12b.",
       "// FSRRA: 34 words indexed by parity*17 + node, fields C0 27b, REC1 23b, E1 2b, REC2 14b, REC3 9b.",
       "const T = {"]
for name in WANT:
    m = re.search(r"localparam logic (?:\[\d+:\d+\] )?" + name + r" ?\[[A-Z_0-9]+\] = '\{([^}]*)\}", src)
    assert m, name
    vals = [num(t) for t in m.group(1).split(",")]
    out.append(f"  {name}: [{', '.join(str(v) for v in vals)}],")
kc = re.search(r"localparam logic \[22:0\] FSCA_KC = (\d+'h[0-9a-fA-F]+);", src)
out.append(f"  FSCA_KC: 0x{num(kc.group(1)):x},")
out.append("};")
open(OUT, "w").write("\n".join(out) + "\n")
print(f"{OUT}: {len(WANT)} tables + KC")
