#!/usr/bin/env python3
"""gen_tests.py -- generate tests.S (timed access kernels) and tests.h (their table) for bscmm.c.

Every kernel is emitted four times, with K = 0, 1, 8 and 24 copies of its body:
    uint32_t t_<name>_<K>(uint32_t r4, uint32_t r5, volatile uint32_t *pmctr /* r6 */);
It runs <setup>, reads the cycle counter, runs the body K times and <drain>, reads the counter again, runs <epi> and
returns the difference.  bscmm.c takes the minimum over several runs and reports
    lat = T(1) - T(0)          (one access, including its drain)
    per = (T(24) - T(8)) / 16  (back-to-back steady state, per body)
Only r0-r7, fr0/fr1 and FPSCR (restored) are touched; r6 = PMCTR low of PRFC0, r7 = start count.
"""
import sys

# name: (setup, body, drain, epi) -- lists of instructions
SZ_ON = ["sts fpscr,r3", "mov #16,r2", "shll16 r2", "or r3,r2", "lds r2,fpscr"]   # FPSCR.SZ = 1 (bit 20)
SZ_OFF = ["lds r3,fpscr"]
T = {
    # uncached / register reads, r4 = address
    "rd_l":     ([], ["mov.l @r4,r1"], [], []),
    "rd_w":     ([], ["mov.w @r4,r1"], [], []),
    "rd_b":     ([], ["mov.b @r4,r1"], [], []),
    "rd_q":     (SZ_ON, ["fmov.s @r4,fr0"], [], SZ_OFF),          # SZ = 1: a 64-bit load into DR0
    "rd_chain": (["mov r4,r1"], ["mov.l @r1,r1"], [], []),         # M[r4] = r4: each load depends on the last
    "rd_use":   ([], ["mov.l @r4,r1", "add r1,r2"], [], []),       # load + immediate use
    "rd_alt":   (["mov r4,r2", "add r5,r2"], ["mov.l @r4,r1", "mov.l @r2,r3"], [], []),   # two addresses
    "rd_stride": (["mov r4,r2"], ["mov.l @r2,r1", "add r5,r2"], [], []),
    # uncached / register writes of the value already there, r4 = address; drained by a read of the same address
    "wr_l":     (["mov.l @r4,r1"], ["mov.l r1,@r4"], ["mov.l @r4,r2"], []),
    "wr_w":     (["mov.w @r4,r1"], ["mov.w r1,@r4"], ["mov.w @r4,r2"], []),
    "wr_b":     (["mov.b @r4,r1"], ["mov.b r1,@r4"], ["mov.b @r4,r2"], []),
    "wr_q":     (SZ_ON + ["fmov.s @r4,fr0"], ["fmov.s fr0,@r4"], ["mov.l @r4,r2"], SZ_OFF),
    "wr_nd":    (["mov.l @r4,r1"], ["mov.l r1,@r4"], [], []),     # writes, no drain read
    "wr_rd":    (["mov.l @r4,r1"], ["mov.l r1,@r4", "mov.l @r4,r2"], [], []),
    "wr_rdalt": (["mov.l @r4,r1", "mov r4,r2", "add r5,r2"], ["mov.l r1,@r4", "mov.l @r2,r3"], [], []),
    "wr_stride": (["mov.l @r4,r1", "mov r4,r2"], ["mov.l r1,@r2", "add r5,r2"], ["mov.l @r4,r3"], []),
    "wr_w_r5":  ([], ["mov.w r5,@r4"], ["mov.w @r4,r2"], []),    # write r5 (a keyed refresh-register value)
    # cached (P1) line operations, r4 = first line, 32-byte stride; r5 = an uncached address read as the drain
    "c_rd":     (["mov r4,r2"], ["mov.l @r2,r1", "add #32,r2"], [], []),
    "c_rd_last": (["mov r4,r2"], ["mov.l @r2,r1", "mov.l @(28,r2),r3", "add #32,r2"], [], []),
    "c_rd_use": (["mov r4,r2"], ["mov.l @r2,r1", "add r1,r3", "add #32,r2"], [], []),
    "c_wr":     (["mov r4,r2"], ["mov.l r1,@r2", "add #32,r2"], ["mov.l @r5,r3"], []),
    "c_ocbwb":  (["mov r4,r2"], ["ocbwb @r2", "add #32,r2"], ["mov.l @r5,r3"], []),
    "c_ocbp":   (["mov r4,r2"], ["ocbp @r2", "add #32,r2"], ["mov.l @r5,r3"], []),
    "c_movca":  (["mov r4,r2"], ["movca.l r0,@r2", "add #32,r2"], [], []),
    # store queues, r4 = SQ0 address of the target (QACR set by the caller), r5 = uncached drain address
    "sq_alt":   (["mov r4,r2", "mov #32,r3"],
                 ["mov.l r0,@r2", "mov.l r0,@(4,r2)", "mov.l r0,@(8,r2)", "mov.l r0,@(12,r2)", "mov.l r0,@(16,r2)",
                  "mov.l r0,@(20,r2)", "mov.l r0,@(24,r2)", "mov.l r0,@(28,r2)", "pref @r2", "xor r3,r2"],
                 ["mov.l @r5,r1"], []),
    "sq_same":  (["mov r4,r2"],
                 ["mov.l r0,@r2", "mov.l r0,@(4,r2)", "mov.l r0,@(8,r2)", "mov.l r0,@(12,r2)", "mov.l r0,@(16,r2)",
                  "mov.l r0,@(20,r2)", "mov.l r0,@(24,r2)", "mov.l r0,@(28,r2)", "pref @r2"],
                 ["mov.l @r5,r1"], []),
    "sq_pref":  (["mov r4,r2"], ["pref @r2"], ["mov.l @r5,r1"], []),
    "sq_pref_nd": (["mov r4,r2"], ["pref @r2"], [], []),
    # run 2 (bscmm2.c)
    "rd_wr":    ([], ["mov.l @r4,r1", "mov.l r1,@r4"], ["mov.l @r4,r2"], []),     # read -> write turnaround
    "tas":      ([], ["tas.b @r4"], [], []),
    "rd_x16":   ([], ["mov.l @r4,r1"] * 16, [], []),                            # long runs: refresh cost
}
# cached line fill beat order: miss on offset a, then a load at offset b of the same line
for a, b in ((0, 8), (0, 16), (0, 24), (16, 0), (16, 8), (16, 24), (8, 0), (24, 16)):
    T[f"c_p{a}_{b}"] = (["mov r4,r2"], [f"mov.l @({a},r2),r1" if a else "mov.l @r2,r1",
                                        f"mov.l @({b},r2),r3" if b else "mov.l @r2,r3", "add #32,r2"], [], [])
KS = (0, 1, 8, 24)

def main():
    s = ["! generated by gen_tests.py -- do not edit", "\t.text"]
    h = ["/* generated by gen_tests.py -- do not edit */",
         "typedef uint32_t (*tfn_t)(uint32_t, uint32_t, volatile uint32_t *);"]
    for name, (setup, body, drain, epi) in T.items():
        for k in KS:
            fn = f"t_{name}_{k}"
            s += ["\t.align 5", f"\t.global _{fn}", f"_{fn}:"]
            s += ["\t" + i for i in setup]
            s += ["\tmov.l @r6,r7"]
            for _ in range(k):
                s += ["\t" + i for i in body]
            s += ["\t" + i for i in drain]
            s += ["\tmov.l @r6,r0"]
            s += ["\t" + i for i in epi]
            s += ["\trts", "\tsub r7,r0"]
            h.append(f"extern uint32_t {fn}(uint32_t, uint32_t, volatile uint32_t *);")
        h.append(f"#define TK_{name} {{ t_{name}_0, t_{name}_1, t_{name}_8, t_{name}_24 }}")
    open(sys.argv[1], "w").write("\n".join(s) + "\n")
    open(sys.argv[2], "w").write("\n".join(h) + "\n")

if __name__ == "__main__":
    main()
