static void refresh_tests(void) {
    uint16_t rtcsr = R16(0xFF80001C), rtcor = R16(0xFF800024);
    /* RTCNT: time 48 increments (bounded poll) */
    {
        irq_mask_t im = irq_disable();
        uint32_t tch[49]; uint16_t vch[49]; int n = 0; uint16_t maxv = 0;
        uint16_t last = R16(0xFF800020);
        uint32_t t0 = pm();
        for (uint32_t it = 0; it < 4000000 && n < 49; it++) {
            uint16_t v = R16(0xFF800020);
            if (v != last) { tch[n] = pm(); vch[n] = v; n++; last = v; if (v > maxv) maxv = v; }
        }
        uint32_t t1 = pm();
        irq_restore(im);
        printf("F RTCNT changes %d in %lu cycles, max %04x, first %04x", n, (unsigned long)(t1 - t0), maxv, vch[0]);
        if (n > 1) printf(", cycles/change avg*100 %lu", (unsigned long)((tch[n - 1] - tch[0]) * 100 / (n - 1)));
        printf("\nF RTCNT seq");
        for (int i = 1; i < n && i < 24; i++) printf(" %02x:%lu", vch[i], (unsigned long)(tch[i] - tch[i - 1]));
        printf("\n");
    }
    /* RFCR over a few windows of ~200k cycles (1 ms) */
    {
        irq_mask_t im = irq_disable();
        uint16_t rv[12]; uint32_t tv[12]; uint16_t cs[12];
        for (int i = 0; i < 12; i++) {
            rv[i] = R16(0xFF800028); cs[i] = R16(0xFF80001C); tv[i] = pm();
            uint32_t s = pm();
            while (pm() - s < 200000) { }
        }
        irq_restore(im);
        printf("F RFCR");
        for (int i = 0; i < 12; i++) printf(" %04x/%04x@%lu", rv[i], cs[i], (unsigned long)(tv[i] - tv[0]));
        printf("\n");
    }
    /* write key of RFCR (only when the OVF interrupt is off) */
    if (!(rtcsr & 0x02)) {
        irq_mask_t im = irq_disable();
        uint16_t a = R16(0xFF800028);
        R16(0xFF800028) = 0x0000;              /* no key */
        uint16_t b = R16(0xFF800028);
        R8(0xFF800028) = 0x00;                 /* byte write */
        uint16_t c = R16(0xFF800028);
        R16(0xFF800028) = 0xA400;              /* key 101001 + value 0 */
        uint16_t d = R16(0xFF800028);
        R16(0xFF800028) = 0xA400 | 0x100;      /* key + 0x100 */
        uint16_t e = R16(0xFF800028);
        R16(0xFF800028) = 0xA500 | 0x005;      /* key with a 1 in bit 8 of the key field? (0xA5 = 1010 0101) */
        uint16_t f = R16(0xFF800028);
        R16(0xFF800028) = 0xA400;              /* back to 0 */
        irq_restore(im);
        printf("K RFCR before %04x nokey0 %04x byte0 %04x key+000 %04x key+100 %04x key+105 %04x\n", a, b, c, d, e, f);
    } else printf("K RFCR skipped (OVIE set)\n");
    /* write key of RTCOR: move it by -1 and back */
    if (rtcor >= 2 && rtcor <= 0xFF) {
        irq_mask_t im = irq_disable();
        uint16_t v = rtcor, m = (uint16_t)(v - 1);
        R16(0xFF800024) = m;                   /* no key */
        uint16_t b = R16(0xFF800024);
        R16(0xFF800024) = 0xA500 | v;
        R8(0xFF800024) = (uint8_t)m;           /* byte write */
        uint16_t c = R16(0xFF800024);
        R16(0xFF800024) = 0xA500 | v;
        R16(0xFF800024) = 0x5A00 | m;          /* wrong key */
        uint16_t d = R16(0xFF800024);
        R16(0xFF800024) = 0xA500 | v;
        R16(0xFF800024) = 0xA500 | m;          /* right key */
        uint16_t e = R16(0xFF800024);
        R16(0xFF800024) = 0xA500 | v;          /* restore */
        uint16_t f = R16(0xFF800024);
        irq_restore(im);
        printf("K RTCOR %04x nokey %04x byte %04x key5A %04x keyA5 %04x restored %04x\n", v, b, c, d, e, f);
    } else printf("K RTCOR skipped (%04x)\n", rtcor);
}

static void mirrors(uint32_t u) {
    /* RAM: marker in our buffer, read through the other three 16 MB images of area 3 */
    uint32_t a = P2(u + 0x100), mk = 0x5AA5C33Cu ^ a;
    R32(a) = mk;
    printf("X RAM %08lx=%08lx +1M %08lx +2M %08lx +3M %08lx (x16MB)\n", (unsigned long)a, (unsigned long)R32(a),
           (unsigned long)R32(a + 0x1000000), (unsigned long)R32(a + 0x2000000), (unsigned long)R32(a + 0x3000000));
    /* VRAM: marker in an unused top word of each path, read through the mirrors */
    uint32_t v64 = 0xA47FFFF8, v32 = 0xA57FFFF8;
    uint32_t s64 = R32(v64), s32 = R32(v32);
    R32(v64) = 0x1234ABCD; R32(v32) = 0x8765FEDC;
    printf("X VRAM64 %08lx +8M %08lx +32M %08lx +40M %08lx | VRAM32 %08lx +8M %08lx +32M %08lx\n",
           (unsigned long)R32(v64), (unsigned long)R32(v64 + 0x800000), (unsigned long)R32(v64 + 0x2000000),
           (unsigned long)R32(v64 + 0x2800000), (unsigned long)R32(v32), (unsigned long)R32(v32 + 0x800000),
           (unsigned long)R32(v32 + 0x2000000));
    R32(v32) = s32; R32(v64) = s64;
    printf("X VRAM restored %08lx %08lx\n", (unsigned long)R32(v64), (unsigned long)R32(v32));
}

