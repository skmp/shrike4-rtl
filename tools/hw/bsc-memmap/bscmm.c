#define R32(a) (*(volatile uint32_t *)(a))
#define R16(a) (*(volatile uint16_t *)(a))
#define R8(a)  (*(volatile uint8_t *)(a))
#define PMCTR ((volatile uint32_t *)0xFF100008)   /* PRFC0 low word */
#define P2(a) ((((uint32_t)(a)) & 0x1FFFFFFF) | 0xA0000000)
#define P1(a) ((((uint32_t)(a)) & 0x1FFFFFFF) | 0x80000000)
#define REPS 9
#define NL 24                                     /* lines a cache kernel touches at K = 24 */

static inline void ocbp(uint32_t a) { __asm__ volatile("ocbp @%0" : : "r"(a) : "memory"); }
static inline void ocbi(uint32_t a) { __asm__ volatile("ocbi @%0" : : "r"(a) : "memory"); }

enum { P_NONE, P_HIT, P_INV, P_DIRTY_VICTIM, P_DIRTY_SELF };

static void prep(int p, uint32_t a) {
    for (int i = 0; i < NL; i++) {
        uint32_t l = a + 32 * i;
        switch (p) {
        case P_HIT: (void)R32(l); break;
        case P_INV: ocbp(l); break;
        case P_DIRTY_VICTIM: ocbp(l); R32(l + 0x4000) = i; break;   /* same OC index (16 KB direct mapped) */
        case P_DIRTY_SELF: ocbp(l); R32(l) = i; break;
        default: break;
        }
    }
}

