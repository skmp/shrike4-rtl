/* bscmm.c -- BSC / external bus / address map measurements on the Dreamcast (spec: rtl/v1/spec/bsc-memmap.md).
 *
 * Part 1: dump every BSC / port register as the BIOS left it (KOS and dcload do not write them, except PCTRA).
 * Part 2: access-width reads of BSC registers (reads only; no BSC configuration register is ever written).
 * Part 3: refresh timer: RTCNT rate, RFCR rate, the write key of RFCR / RTCOR (RTCOR is only ever moved by one count
 *         and put back at once; RFCR is a refresh counter nobody on the DC uses).
 * Part 4: mirrors of system RAM (area 3) and texture memory (area 1), with markers written to our own buffer / to
 *         unused top-of-VRAM words, which are restored.
 * Part 5: timed access kernels (tests.S, generated by gen_tests.py): uncached RAM / Holly / G1 / G2 / VRAM / P4
 *         accesses, operand-cache line fills and write-backs, store-queue bursts.  Every write writes back the value
 *         just read (or goes to our own buffer / saved-and-restored VRAM), so nothing outside this program changes.
 * All timing runs with interrupts masked; each value is the minimum over REPS runs of PRFC0 (CPU cycles).
 * Nothing here can wait forever: every polling loop is bounded. */
#include <kos.h>
#include <stdio.h>
