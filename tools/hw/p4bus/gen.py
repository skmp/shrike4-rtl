#!/usr/bin/env python3
# gen.py -- generates p4b_asm.S and p4b_tab.h for the WI-P4 P4-bridge probe p4b.c (rtl/v1/SOC.md 9.13).
#
# Every measured function has the shape
#     mov.w @r6, r3          ! align: a Pclk read of IPRA (its ack is a fixed offset from a Pclk edge)
#     k x add #1, r0         ! fillers: move the bracket's first read by one Icyc each (once past the pairing slots)
#     mov.l @r1, r2          ! A = PMCTR0L
#     <body>                 ! the accesses under test
#     mov.l @r1, r3          ! B = PMCTR0L
#     return B - A
# for k = 0 .. NK-1, so the table over k shows each body at every Pclk phase of A.  The "rd16" body (one TCR1 read) is
# the phase meter: the RTL gives 16 / 17 / 18 / 19 by the phase of A.
# Registers (arguments): r4 = TCR1, r5 = TCOR1, r6 = IPRA, r7 = PMCTR0L; r8 = 0 and r9 = 0xFFFFFFFF are the write values
# (saved / restored: callee-saved).  TMU1 is stopped by the caller, so the TCR1 / TCOR1 writes are harmless.
import os

NK = 12
W16 = "mov.w r8,@r4"          # TCR1 <- 0
W32 = "mov.l r9,@r5"          # TCOR1 <- 0xFFFFFFFF
R16 = "mov.w @r4,r0"          # TCR1
R16O = "mov.w @r6,r0"         # IPRA (another module)
R32 = "mov.l @r5,r0"          # TCOR1

SEQS = [
    ("none",      []),
    ("rd16",      [R16]),
    ("rd16o",     [R16O]),
    ("rd32",      [R32]),
    ("rd16x16",   [R16] * 16),
    ("rd32x16",   [R32] * 16),
    ("rd16_rd16o", [R16, R16O]),
    ("w16x1",     [W16]),
    ("w16x2",     [W16] * 2),
    ("w16x3",     [W16] * 3),
    ("w16x4",     [W16] * 4),
    ("w16x16",    [W16] * 16),
    ("w32x1",     [W32]),
    ("w32x2",     [W32] * 2),
    ("w32x3",     [W32] * 3),
    ("w32x4",     [W32] * 4),
    ("w32x16",    [W32] * 16),
    ("w32_w16",   [W32, W16]),
    ("w32_w16_w16", [W32, W16, W16]),
    ("w16_w32",   [W16, W32]),
    ("w16_w32_w16", [W16, W32, W16]),
    ("w32_r16o",  [W32, R16O]),
    ("w32_r32",   [W32, R32]),
    ("w32x4_r16o", [W32] * 4 + [R16O]),
    ("w16_r16",   [W16, R16]),
    ("w16_r16o",  [W16, R16O]),
    ("w16_r16x2", [W16, R16] * 2),
    ("w16_r16x3", [W16, R16] * 3),
    ("w16_r16x8", [W16, R16] * 8),
    ("w16_r16ox8", [W16, R16O] * 8),
    ("w32_r32x8", [W32, R32] * 8),
]

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    a = []
    a.append("! p4b_asm.S -- GENERATED by gen.py (WI-P4 P4-bridge probe); do not edit.")
    a.append("    .text")
    for name, body in SEQS:
        for k in range(NK):
            a.append("    .align 5")
            a.append(f"_m_{name}_{k}:")
            a.append("    mov.l   r8,@-r15")
            a.append("    mov.l   r9,@-r15")
            a.append("    mov     #0,r8")
            a.append("    mov     #-1,r9")
            a.append("    mov     r7,r1")
            a.append("    mov.w   @r6,r3")
            for _ in range(k):
                a.append("    add     #1,r0")
            a.append("    mov.l   @r1,r2")
            for ins in body:
                a.append("    " + ins)
            a.append("    mov.l   @r1,r3")
            a.append("    sub     r2,r3")
            a.append("    mov.l   @r15+,r9")
            a.append("    mov.l   @r15+,r8")
            a.append("    rts")
            a.append("    mov     r3,r0")
    a.append("    .align 2")
    a.append("    .globl _p4b_tab")
    a.append("_p4b_tab:")
    for name, _ in SEQS:
        for k in range(NK):
            a.append(f"    .long   _m_{name}_{k}")
    with open(os.path.join(here, "p4b_asm.S"), "w") as f:
        f.write("\n".join(a) + "\n")
    h = ["/* p4b_tab.h -- GENERATED by gen.py; do not edit. */",
         f"#define P4B_NK {NK}", f"#define P4B_NS {len(SEQS)}",
         "static const char *const p4b_names[P4B_NS] = {"]
    h += [f'    "{n}",' for n, _ in SEQS]
    h.append("};")
    with open(os.path.join(here, "p4b_tab.h"), "w") as f:
        f.write("\n".join(h) + "\n")

if __name__ == "__main__":
    main()
